const (
	definitionName = "kyc_verification"
	maxImageBytes  = 5 << 20 // 5 MB per image
)

var (
	ErrAlreadyPending  = errors.New("kyc already pending review")
	ErrAlreadyVerified = errors.New("kyc already verified")
	ErrBadImage        = errors.New("invalid kyc image")
)

type Service struct {
	pool   *pgxpool.Pool
	q      *store.Queries
	engine *workflow.Engine
	files  storage.Store
}

func NewService(pool *pgxpool.Pool, engine *workflow.Engine, files storage.Store) *Service {
	return &Service{pool: pool, q: store.New(pool), engine: engine, files: files}
}

// ValidateImage enforces that data is a real, bounded JPEG or PNG (see InspectImage).
func ValidateImage(data []byte) error {
	_, err := InspectImage(data)
	return err
}

type SubmitResult struct {
	RequestID uuid.UUID `json:"request_id"`
	Status    string    `json:"status"`
	CreatedAt time.Time `json:"created_at"`
}

// Submit writes both images to storage FIRST, then atomically creates the
// kyc_requests row, flips the user to pending (guarded: only none|rejected
// may enter) and starts the kyc_verification workflow. An orphaned file on tx
// failure is acceptable; a DB row pointing at a missing file is not.
func (s *Service) Submit(ctx context.Context, userID uuid.UUID, idCard, selfie []byte) (SubmitResult, error) {
	if err := ValidateImage(idCard); err != nil {
		return SubmitResult{}, err
	}
	if err := ValidateImage(selfie); err != nil {
		return SubmitResult{}, err
	}
	u, err := s.q.GetUserStatusByID(ctx, userID)
	if err != nil {
		return SubmitResult{}, err
	}
	switch u.KycStatus {
	case store.KycStatusPending, store.KycStatusManualReview:
		return SubmitResult{}, ErrAlreadyPending
	case store.KycStatusAutoApproved, store.KycStatusVerified:
		return SubmitResult{}, ErrAlreadyVerified
	}

	requestID := uuid.New()
	// The key extension follows the content (InspectImage already proved it), so a PNG is
	// never stored under a .jpg name.
	idCardKey := KeyFor(requestID.String(), "id_card", idCard)
	selfieKey := KeyFor(requestID.String(), "selfie", selfie)
	if err := s.files.Put(ctx, idCardKey, idCard); err != nil {
		return SubmitResult{}, err
	}
	if err := s.files.Put(ctx, selfieKey, selfie); err != nil {
		return SubmitResult{}, err
	}

	tx, err := s.pool.Begin(ctx)
	if err != nil {
		return SubmitResult{}, err
	}
	defer tx.Rollback(ctx)
	qtx := s.q.WithTx(tx)

	n, err := qtx.MarkUserKycPending(ctx, userID)
	if err != nil {
		return SubmitResult{}, err
	}
	if n == 0 {
		return SubmitResult{}, ErrAlreadyPending // raced another submit
	}
	row, err := qtx.InsertKYCRequest(ctx, store.InsertKYCRequestParams{
		UserID: userID, IDCardUrl: idCardKey, SelfieUrl: selfieKey,
	})
	if err != nil {
		return SubmitResult{}, err
	}
	// NOTE: the row id is generated by the DB, not requestID — storage keys
	// intentionally use their own uuid so a failed tx never collides.
	if _, err := s.engine.Start(ctx, tx, definitionName, uuid.Nil, map[string]any{
		"kyc_request_id": row.ID.String(),
	}); err != nil {
		return SubmitResult{}, err
	}
	if err := tx.Commit(ctx); err != nil {
		return SubmitResult{}, err
	}
	return SubmitResult{RequestID: row.ID, Status: string(row.Status), CreatedAt: row.CreatedAt.Time}, nil
}

type Status struct {
	KycStatus string         `json:"kyc_status"`
	Latest    *LatestRequest `json:"latest_request,omitempty"`
}

type LatestRequest struct {
	ID        uuid.UUID `json:"id"`
	Status    string    `json:"status"`
	AiScore   *int      `json:"ai_score,omitempty"`
	AiReasons any       `json:"ai_reasons,omitempty"`
	CreatedAt time.Time `json:"created_at"`
}

func (s *Service) Status(ctx context.Context, userID uuid.UUID) (Status, error) {
	u, err := s.q.GetUserStatusByID(ctx, userID)
	if err != nil {
		return Status{}, err
	}
	out := Status{KycStatus: string(u.KycStatus)}
	latest, err := s.q.GetLatestKYCByUser(ctx, userID)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return out, nil
		}
		return Status{}, err
	}
	lr := &LatestRequest{ID: latest.ID, Status: string(latest.Status), CreatedAt: latest.CreatedAt.Time}
	if latest.AiScore >= 0 {
		score := int(latest.AiScore)
		lr.AiScore = &score
	}
	if len(latest.AiReasons) > 0 {
		lr.AiReasons = jsonRaw(latest.AiReasons)
	}
	out.Latest = lr
	return out, nil
}

// jsonRaw lets already-encoded JSONB pass through the response unrescaped.
type jsonRaw []byte

func (j jsonRaw) MarshalJSON() ([]byte, error) { return j, nil }
